func TestDatabaseIDPairRejectsCrossStoreAndRecreatedStoreReplay(t *testing.T) {
	ctx := context.Background()
	f := newFixture(t, BackendPublicRepo)
	f.appendRecord(t, 0)
	storeA, _ := newStore(t, f)
	defer storeA.Close()
	observation := f.observation(1)
	proposalA := prepareFirstUse(t, storeA, observation, f.payload)
	storeB, storeBDir := newStore(t, f)
	proposalB := prepareFirstUse(t, storeB, observation, f.payload)
	_, err := storeB.Accept(ctx, ModeFirstUse, proposalA.StateToken, observation, f.payload, proposalA.Confirmation)
	requireErrorMetadata(t, err, ErrConsent, StageAccept, ReasonStale)
	_, present, err := storeB.Load(ctx)
	require.NoError(t, err)
	require.False(t, present)
	oldStoreBID := storeB.databaseID
	require.NoError(t, storeB.Close())
	for _, name := range []string{"publication.db", "publication.db-wal", "publication.db-shm", "publication.db.lock"} {
		removeErr := os.Remove(filepath.Join(storeBDir, name))
		require.True(t, removeErr == nil || errors.Is(removeErr, os.ErrNotExist))
	}
	recreated, err := Open(storeBDir, f.binding)
	require.NoError(t, err)
	defer recreated.Close()
	assert.NotEqual(t, oldStoreBID, recreated.databaseID)
	_, err = recreated.Accept(ctx, ModeFirstUse, proposalB.StateToken, observation, f.payload, proposalB.Confirmation)
	requireErrorMetadata(t, err, ErrConsent, StageAccept, ReasonStale)
	freshProposal, err := recreated.Prepare(ctx, ModeFirstUse, observation, f.payload)
	require.NoError(t, err)
	freshFloor, err := recreated.Accept(ctx, ModeFirstUse, freshProposal.StateToken, observation, f.payload, freshProposal.Confirmation)
	require.NoError(t, err)
	assert.Equal(t, uint64(1), freshFloor.Generation)
	assert.NotEqual(t, oldStoreBID, freshFloor.DatabaseID)
	firstFloor, err := storeA.Accept(ctx, ModeFirstUse, proposalA.StateToken, observation, f.payload, proposalA.Confirmation)
	require.NoError(t, err)
	assert.NotEqual(t, storeA.databaseID, storeB.databaseID)
	alternate := fixtureRecord(t, f, 0, nil, 0x71)
	alternateObservation := singleRecordObservation(t, f, alternate)
	replacement, err := storeA.Prepare(ctx, ModeReplaceFloor, alternateObservation, f.payload)
	require.NoError(t, err)
	_, err = storeA.Accept(ctx, ModeReplaceFloor, replacement.StateToken, alternateObservation, f.payload, replacement.Confirmation)
	require.NoError(t, err)
	back, err := storeA.Prepare(ctx, ModeReplaceFloor, observation, f.payload)
	require.NoError(t, err)
	assert.Equal(t, ReasonFork, back.Reason)
	finalFloor, err := storeA.Accept(ctx, ModeReplaceFloor, back.StateToken, observation, f.payload, back.Confirmation)
	require.NoError(t, err)
	assert.Equal(t, firstFloor.Sequence, finalFloor.Sequence)
	assert.Equal(t, firstFloor.RecordCID, finalFloor.RecordCID)
	assert.Equal(t, uint64(3), finalFloor.Generation)
	assert.Equal(t, firstFloor.DatabaseID, finalFloor.DatabaseID)
	_, err = storeA.Accept(ctx, ModeFirstUse, proposalA.StateToken, observation, f.payload, proposalA.Confirmation)
	requireErrorMetadata(t, err, ErrConsent, StageAccept, ReasonStale)
	loaded, present, err := storeA.Load(ctx)
	require.NoError(t, err)
	require.True(t, present)
	assert.Equal(t, finalFloor, loaded)
}

func TestABAAcceptedAdvanceTokenIsStaleAfterReturningToSamePosition(t *testing.T) {
	ctx := context.Background()
	f := newFixture(t, BackendPublicRepo)
	f.appendRecord(t, 0)
	store, _ := newStore(t, f)
	defer store.Close()
	original := f.observation(1)
	first := prepareFirstUse(t, store, original, f.payload)
	firstFloor, err := store.Accept(ctx, ModeFirstUse, first.StateToken, original, f.payload, first.Confirmation)
	require.NoError(t, err)
	advanceToken, err := store.Prepare(ctx, ModeAdvance, original, f.payload)
	require.NoError(t, err)
	assert.Equal(t, "same", advanceToken.Stop)
	alternate := fixtureRecord(t, f, 0, nil, 0x71)
	alternateObs := singleRecordObservation(t, f, alternate)
	replacement, err := store.Prepare(ctx, ModeReplaceFloor, alternateObs, f.payload)
	require.NoError(t, err)
	_, err = store.Accept(ctx, ModeReplaceFloor, replacement.StateToken, alternateObs, f.payload, replacement.Confirmation)
	require.NoError(t, err)
	back, err := store.Prepare(ctx, ModeReplaceFloor, original, f.payload)
	require.NoError(t, err)
	assert.Equal(t, ReasonFork, back.Reason)
	final, err := store.Accept(ctx, ModeReplaceFloor, back.StateToken, original, f.payload, back.Confirmation)
	require.NoError(t, err)
	assert.Equal(t, firstFloor.RecordCID, final.RecordCID)
	assert.Equal(t, uint64(3), final.Revision)
	assert.Equal(t, uint64(3), final.Generation)
	before := readLogicalRows(t, store.conn)
	result, err := store.Accept(ctx, ModeAdvance, advanceToken.StateToken, original, f.payload, [32]byte{})
	requireErrorMetadata(t, err, ErrConsent, StageAccept, ReasonStale)
	assert.Equal(t, Floor{}, result)
	assert.Equal(t, before, readLogicalRows(t, store.conn))
	loaded, present, err := store.Load(ctx)
	require.NoError(t, err)
	require.True(t, present)
	assert.Equal(t, final, loaded)
}
